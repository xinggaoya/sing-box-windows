/**
 * 用节点名里的地名反查国家码的正则表。
 *
 * `flag-icons` 只能按「已经知道国家码」渲染图标，因此节点名是纯中文 / 日文时
 * 需要先从地名推断出码。
 */
export const COUNTRY_NAME_PATTERNS: ReadonlyArray<readonly [RegExp, string]> = [
  [/东京|東京|大阪/, 'JP'],
  [/香港|hong\s*kong/i, 'HK'],
  [/台湾|台灣|taiwan/i, 'TW'],
  [/美国|美國|洛杉矶|洛杉磯|西雅图|西雅圖|纽约|紐約|america|united\s*states/i, 'US'],
  [/英国|英國|伦敦|倫敦|britain|united\s*kingdom/i, 'GB'],
  [/首尔|首爾|korea/i, 'KR'],
  [/澳洲/, 'AU'],
  [/沙特阿拉伯|沙特|saudi/i, 'SA'],
  [/阿联酋|阿聯酋|uae|united\s*arab\s*emirates/i, 'AE'],
]

/**
 * 「信息节点」的特征 —— 机场订阅里常见的流量 / 到期 / 官网提示条目，
 * 它们不是真实节点，不应参与筛选与测速。
 */
export const INFORMATIONAL_NODE_PATTERNS: ReadonlyArray<RegExp> = [
  /^剩余流量[:：]/,
  /^距离下次重置剩余[:：]/,
  /^套餐到期[:：]/,
  /^官网[:：]/,
  /^星云[:：]/,
  /^https?:\/\//i,
]

